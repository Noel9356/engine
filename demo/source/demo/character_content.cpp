constexpr float pi = glm::pi<float>();

// Weights below this delta are treated as unchanged (no reupload).
constexpr float kWeightEpsilon = 5.0e-4f;

// Loads a colored OBJ produced by scripts/build_character_parts.py:
// "v x y z r g b" vertices, "vn" normals, "f a//a b//b c//c" triangles
// (1-based), then any number of morph blocks: "m <name>" followed by one
// "d dx dy dz" per vertex in vertex order. Returns false when the file is
// missing or holds no triangles.
bool loadPartObj(const std::filesystem::path &path, MeshData &outMesh, std::vector<std::string> &outMorphNames,
    std::vector<std::vector<glm::vec3>> &outMorphDeltas, std::vector<std::uint32_t> &outMorphVertexIds)
{
    std::FILE *file = std::fopen(path.string().c_str(), "rb");
    if (file == nullptr)
    {
        return false;
    }
    std::vector<glm::vec3> positions;
    std::vector<glm::vec3> colors;
    std::vector<glm::vec3> normals;
    char                   line[512];
    bool                   inMorph = false;
    while (std::fgets(line, sizeof(line), file) != nullptr)
    {
        if (line[0] == 'v' && line[1] == ' ')
        {
            float x = 0.0f, y = 0.0f, z = 0.0f, r = 1.0f, g = 1.0f, b = 1.0f;
            if (std::sscanf(line + 2, "%f %f %f %f %f %f", &x, &y, &z, &r, &g, &b) < 3)
            {
                std::fclose(file);
                return false;
            }
            positions.emplace_back(x, y, z);
            colors.emplace_back(r, g, b);
            inMorph = false;
        }
        else if (line[0] == 'v' && line[1] == 'n')
        {
            float x = 0.0f, y = 0.0f, z = 0.0f;
            if (std::sscanf(line + 3, "%f %f %f", &x, &y, &z) == 3)
            {
                normals.emplace_back(x, y, z);
            }
        }
        else if (line[0] == 'f' && line[1] == ' ')
        {
            unsigned a = 0, an = 0, b = 0, bn = 0, c = 0, cn = 0;
            // "f v//vn v//vn v//vn" is what the pipeline writes; plain
            // "f v v v" is accepted for hand-made parts without normals.
            if (std::sscanf(line + 2, "%u//%u %u//%u %u//%u", &a, &an, &b, &bn, &c, &cn) != 6
                && std::sscanf(line + 2, "%u %u %u", &a, &b, &c) != 3)
            {
                std::fclose(file);
                return false;
            }
            const std::uint32_t base = static_cast<std::uint32_t>(outMesh.vertices.size());
            for (const unsigned index : {a, b, c})
            {
                Vertex vertex;
                vertex.position = positions[index - 1];
                vertex.color    = colors[index - 1];
                vertex.normal   = normals.empty()
                                    ? glm::vec3(0.0f, 1.0f, 0.0f)
                                    : normals[std::min<std::size_t>(an > 0 ? an - 1 : 0, normals.size() - 1)];
                vertex.uv       = {0.0f, 0.0f};
                outMesh.vertices.push_back(vertex);
                // Morph deltas are authored per source (welded) vertex; the
                // expanded corner keeps that id so the runtime applies the
                // right delta to each corner of the same welded vertex.
                outMorphVertexIds.push_back(index - 1);
            }
            outMesh.indices.insert(outMesh.indices.end(), {base, base + 1, base + 2});
            inMorph = false;
        }
        else if (line[0] == 'm' && line[1] == ' ')
        {
            char name[64] = {};
            if (std::sscanf(line + 2, "%63s", name) == 1)
            {
                outMorphNames.emplace_back(name);
                outMorphDeltas.emplace_back();
                outMorphDeltas.back().reserve(positions.size());
                inMorph = true;
            }
        }
        else if (line[0] == 'd' && line[1] == ' ' && inMorph && !outMorphDeltas.empty())
        {
            float x = 0.0f, y = 0.0f, z = 0.0f;
            if (std::sscanf(line + 2, "%f %f %f", &x, &y, &z) == 3)
            {
                outMorphDeltas.back().emplace_back(x, y, z);
            }
        }
    }
    std::fclose(file);
    // A morph block must carry one delta per vertex; a partial block would
    // desync positions and deltas, so truncate it instead of guessing.
    for (std::size_t index = 0; index < outMorphDeltas.size(); ++index)
    {
        if (outMorphDeltas[index].size() != positions.size())
        {
            outMorphDeltas[index].clear();
            outMorphNames[index].clear();
        }
    }
    return !outMesh.indices.empty();
}

// A lofted tube used by the procedural neck piece: cross-sections bottom to
// top, each an N-gon with its own center and radii. Kept minimal because the
// neck is the only runtime-generated mesh (see buildNeckPieceGeometry).
MeshData makeTubeMesh(const std::vector<glm::vec3> &centers, const std::vector<glm::vec2> &radii,
    std::uint32_t segments, const glm::vec3 &baseColor)
{
    MeshData          mesh;
    const std::size_t levelCount = centers.size();
    if (levelCount < 2 || segments < 3)
    {
        return mesh;
    }
    mesh.vertices.reserve(levelCount * segments + 2);
    for (std::size_t level = 0; level < levelCount; ++level)
    {
        const float v = static_cast<float>(level) / static_cast<float>(levelCount - 1);
        for (std::uint32_t s = 0; s < segments; ++s)
        {
            const float angle = static_cast<float>(s) * (2.0f * pi / static_cast<float>(segments));
            const float cosA  = std::cos(angle);
            const float sinA  = std::sin(angle);
            Vertex      vertex;
            vertex.position = centers[level] + glm::vec3(radii[level].x * cosA, 0.0f, radii[level].y * sinA);
            glm::vec3 below = level > 0 ? centers[level] - centers[level - 1] : glm::vec3(0.0f, 1.0f, 0.0f);
            glm::vec3 above
                = level + 1 < levelCount ? centers[level + 1] - centers[level] : glm::vec3(0.0f, 1.0f, 0.0f);
            glm::vec3       axis = glm::normalize(below + above);
            const glm::vec3 radial(cosA, 0.0f, sinA);
            vertex.normal = glm::normalize(radial - axis * glm::dot(radial, axis));
            vertex.color  = glm::clamp(baseColor * (0.88f + 0.12f * v), glm::vec3(0.0f), glm::vec3(1.0f));
            vertex.uv     = {static_cast<float>(s) / static_cast<float>(segments), v};
            mesh.vertices.push_back(vertex);
        }
    }
    for (std::size_t level = 0; level + 1 < levelCount; ++level)
    {
        for (std::uint32_t s = 0; s < segments; ++s)
        {
            const std::uint32_t sNext = (s + 1) % segments;
            const std::uint32_t a     = static_cast<std::uint32_t>(level * segments) + s;
            const std::uint32_t b     = static_cast<std::uint32_t>(level * segments) + sNext;
            const std::uint32_t c     = static_cast<std::uint32_t>((level + 1) * segments) + s;
            const std::uint32_t d     = static_cast<std::uint32_t>((level + 1) * segments) + sNext;
            mesh.indices.insert(mesh.indices.end(), {a, c, d, a, d, b});
        }
    }
    // The top cap hides inside the head's skirt; the bottom stays open
    // inside the torso's neck.
    glm::vec3           topCentroid(0.0f);
    for (std::uint32_t s = 0; s < segments; ++s)
    {
        topCentroid += mesh.vertices[(levelCount - 1) * segments + s].position;
    }
    topCentroid /= static_cast<float>(segments);
    const std::uint32_t centerIndex = static_cast<std::uint32_t>(mesh.vertices.size());
    Vertex              centerVertex{};
    centerVertex.position = topCentroid;
    centerVertex.normal   = glm::vec3(0.0f, 1.0f, 0.0f);
    centerVertex.color    = mesh.vertices[(levelCount - 1) * segments].color;
    centerVertex.uv       = {0.5f, 1.0f};
    mesh.vertices.push_back(centerVertex);
    for (std::uint32_t s = 0; s < segments; ++s)
    {
        const std::uint32_t current = static_cast<std::uint32_t>((levelCount - 1) * segments) + s;
        const std::uint32_t next
            = static_cast<std::uint32_t>((levelCount - 1) * segments) + (s + 1) % segments;
        mesh.indices.insert(mesh.indices.end(), {current, centerIndex, next});
    }
    return mesh;
}

// The procedural neck piece for a junction radius: a tapered tube that
// sinks into the torso's neck below and rises into the head's skirt above,
// with both overlaps absorbing the cut boundaries at either end. The tube
// flares slightly at the top so the head's skirt ring always swallows the
// cap from every viewing angle.
MeshData buildNeckPieceGeometry(float radius)
{
    const glm::vec3 skin(0.74f, 0.55f, 0.43f);
    return makeTubeMesh(
        {
            glm::vec3(0.0f, -0.060f, 0.001f),
            glm::vec3(0.0f, 0.045f, 0.002f),
            glm::vec3(0.0f, 0.130f, 0.003f),
            glm::vec3(0.0f, 0.205f, 0.003f),
        },
        {
            glm::vec2(radius * 1.24f, radius * 1.24f),
            glm::vec2(radius * 1.12f, radius * 1.12f),
            glm::vec2(radius * 1.05f, radius * 1.05f),
            glm::vec2(radius * 1.02f, radius * 1.02f),
        },
        22,
        skin);
}

// ---- content registration helpers ------------------------------------------

ConnectorAnchorDefinition partLocalAnchor(float x, float y, float z, float yawDegrees = 0.0f)
{
    ConnectorAnchorDefinition anchor{};
    anchor.space             = AnchorSpace::PartLocal;
    anchor.translation[0]    = x;
    anchor.translation[1]    = y;
    anchor.translation[2]    = z;
    const glm::quat rotation = glm::angleAxis(glm::radians(yawDegrees), glm::vec3(0.0f, 1.0f, 0.0f));
    anchor.rotation[0]       = rotation.x;
    anchor.rotation[1]       = rotation.y;
    anchor.rotation[2]       = rotation.z;
    anchor.rotation[3]       = rotation.w;
    return anchor;
}

ConnectorAnchorDefinition jointAnchor(const char *jointSemantic, float x, float y, float z, float yawDegrees = 0.0f)
{
    ConnectorAnchorDefinition anchor = partLocalAnchor(x, y, z, yawDegrees);
    anchor.space                     = AnchorSpace::Joint;
    anchor.jointSemantic             = jointSemantic;
    return anchor;
}

ParameterBinding jointTranslationBinding(const char *parameter, const char *jointSemantic, float x, float y, float z)
{
    ParameterBinding binding{};
    binding.parameter = parameter;
    binding.target    = ParameterBindingTarget::JointTranslation;
    binding.targetId  = jointSemantic;
    binding.offset[0] = x;
    binding.offset[1] = y;
    binding.offset[2] = z;
    return binding;
}

ParameterBinding scaleBinding(const char *parameter, ParameterBindingTarget target, float scale)
{
    ParameterBinding binding{};
    binding.parameter = parameter;
    binding.target    = target;
    binding.scale     = scale;
    return binding;
}

